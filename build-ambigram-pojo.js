// build-ambigram-pojo.js — offline generator for the punctuators ambigram POJO.
//
// Regenerates the { word: partner } map used by the Ambigrambador wordplay so it
// matches Spin Nids exactly: a word is a 180° ambigram iff every letter has a 180°
// reading AND the reversed+mapped result is itself a real word in enable1.txt.
//
// This is the SAME logic as Spin Nids' allAmbigramTypes(...) 'rot' branch:
//   rotLetters = word.split('').reverse().map(l => AM[l][2])
//   keep if rotLetters.every(Boolean) && WORDS.has(rotLetters.join('').toLowerCase())
//
// Usage:  node build-ambigram-pojo.js
// Writes the generated literal to scratchpad for review before wiring it in.

const fs = require("fs");

// ── Spin Nids' AM map (verbatim). Index [2] is the 180° reading; null = unreadable.
const AM = {
  a: ["a", null, "e", null],   e: ["e", null, "a", null],
  b: ["b", null, "g", null],   q: ["q", null, "b", null],
  c: ["c", "n", null, "u"],    u: ["u", "s", "n", "s"],
  d: ["d", null, "p", null],
  f: ["f", null, "t", null],   p: ["p", null, "d", null],
  g: ["g", "oo", "g", "oo"],
  h: ["h", null, "y", null],   y: ["y", null, "R", null],
  i: ["i", null, "i", null],
  j: ["j", "L", "r", null],    r: ["r", null, "j", "L"],
  l: ["l", null, "l", null],
  m: ["m", "B", "w", "E"],     w: ["w", "E", "m", "B"],
  n: ["n", "s", "u", "s"],     s: ["s", "u", "s", "n"],
  o: ["o", "o", "o", "o"],
  t: ["t", "t", "t", "t"],     x: ["x", "x", "x", "x"],
  z: ["z", "N", "z", "N"],
  A: ["A", null, "V", null],   V: ["V", null, "A", null],
  B: ["B", "w", "E", "m"],
  C: ["C", "n", "D", "u"],     D: ["D", "U", "G", "n"],
  E: ["E", "m", "B", "w"],     F: ["F", "m", "J", null],
  G: ["G", null, null, "U"],
  H: ["H", "I", "H", "I"],     I: ["I", "H", "I", "H"],
  J: ["J", "l", "r", null],
  L: ["L", "r", "T", null],    T: ["T", null, "L", "r"],
  M: ["M", "B", "W", "E"],     W: ["W", "E", "M", "B"],
  N: ["N", "Z", "N", "Z"],     Z: ["Z", "N", "Z", "N"],
  O: ["O", "O", "O", "O"],     P: ["P", null, "d", null],
  R: ["R", null, "y", null],   S: ["S", "u", "S", "n"],
  Y: ["Y", "Y", "h", "Y"],
  "!": ["!", null, "i", null],
};

const words = fs
  .readFileSync("enable1.txt", "utf8")
  .split(/\r?\n/)
  .map((w) => w.trim().toLowerCase())
  .filter(Boolean);
const WORDS = new Set(words);

// Compute the 180° partner exactly as Spin Nids does.
function rot180(word) {
  const rot = word
    .split("")
    .reverse()
    .map((l) => (AM[l] ? AM[l][2] : null));
  if (!rot.every(Boolean)) return null;
  const partner = rot.join("");
  // Store lowercased for display: punctuators renders real text in a normal font
  // (not Spin Nids' custom ambigram glyphs), so a stray uppercase 'R' from the
  // y->R mapping would read wrong. The lowercased form is the validated real word.
  return WORDS.has(partner.toLowerCase()) ? partner.toLowerCase() : null;
}

const pojo = {};
let total = 0,
  multi = 0;
for (const word of WORDS) {
  const partner = rot180(word);
  if (partner) {
    pojo[word] = partner;
    total++;
    if (word.length >= 2) multi++;
  }
}

// Emit a stable, sorted literal.
const keys = Object.keys(pojo).sort();
const body = keys.map((k) => `  ${JSON.stringify(k)}: ${JSON.stringify(pojo[k])},`).join("\n");
const literal = `// AUTO-GENERATED by build-ambigram-pojo.js from enable1.txt — do not hand-edit.\n// ${total} 180° ambigram pairs (real word -> real word), matching Spin Nids' AM map.\nconst ambigramPOJO = {\n${body}\n};`;

// Patch AmbigramFunc.js in place: replace the existing `const ambigramPOJO = {...};`
// block, leaving the helper functions below it untouched.
const funcPath = "AmbigramFunc.js";
const src = fs.readFileSync(funcPath, "utf8");
const replaced = src.replace(/(?:\/\/[^\n]*\n)*const ambigramPOJO = \{[\s\S]*?\n\};/, literal);
if (replaced === src) {
  console.error("ERROR: could not locate the ambigramPOJO block in AmbigramFunc.js");
  process.exit(1);
}
fs.writeFileSync(funcPath, replaced);

console.log(`patched: ${funcPath}`);
console.log(`enable1.txt words:        ${WORDS.size}`);
console.log(`180° ambigram pairs:      ${total}`);
console.log(`  of those length >= 2:   ${multi}`);
console.log(`  single-letter pairs:    ${total - multi}`);
console.log("\nsample (first 30, sorted):");
console.log(keys.slice(0, 30).map((k) => `  ${k} -> ${pojo[k]}`).join("\n"));
console.log("\nsample longer words:");
console.log(
  keys.filter((k) => k.length >= 5).slice(0, 30).map((k) => `  ${k} -> ${pojo[k]}`).join("\n"),
);
