/* serifinFunc.js — the sentence side of Serifin's Strokes.
   docs/punctuators-serifin.md §5 (the span), §6.1 (the cycle), §5.2 (the frozen box).

   serifinPOJO.js owns the data (generated by build-serifin-pojo.js from the §3.1 stroke table);
   this file owns which LETTERS in a typed sentence are targets, what their markup looks like, and
   what one hit does to the state on the span. index.js owns the hero side.

   THE TARGET IS A LETTER, NOT A WORD, and that is the whole mode (§1.1). Projectiles in this game
   fly straight up and cannot be aimed, so a shot's x-position is the only selector the engine has:
   with word targets that means "pick a word", and with letter targets it means you walk Serifin
   along under the sentence and stop beneath THE `o` IN `adopt`. Everything awkward below — the
   wrapper, the hand-pushed nodeArr entries, the frozen widths — is the price of that, and it is
   the price of the only honest reading of the power.

   Three things here are load-bearing:

   1. THE TABLE IS A Map, NOT A PLAIN OBJECT. `constructor` and `prototype` are both real words in
      2of12.txt (verified) and both are keys in the shipped POJO's input, so `{}[word]` would hand
      back Object's own constructor — a truthy function — for any word the table lacks. §3.5 rule 3
      calls for CaretFunc.js's own-property `entryFor`; a Map is the ladder's answer to the same
      trap and is free here, because the compact POJO strings have to be parsed into a structure at
      load time anyway. Same decision, stronger guarantee.
   2. THE WORD IS WRAPPED IN AN <i>, AND THE LETTER SPANS ARE PUSHED INTO nodeArr BY HAND. The
      observer in waitForElement() reads a mutation's addedNodes, which lists only DIRECTLY
      inserted nodes — never their descendants — so a span inside the wrapper is invisible to it and
      the team comes back empty (the white-screen footgun, hit three times already). index.js does
      the push; see §5.1. The wrapper exists for `white-space: nowrap`: each letter is an
      inline-block and inline-level boxes break between each other, so without it a long word would
      split mid-word. <i> inside a target span is proven safe; a nested <span> is the footgun.
   3. THE LETTER'S BOX IS FROZEN BEFORE PLAY (freezeLetterBoxes). #output centres every line
      INDIVIDUALLY, so any width change anywhere in a line slides the whole line sideways, and `l`
      and `t` are not the same width. ApostroPharaoh's squash was built around the same rule.
*/

export const SERIFIN_ID = "Serifin ✎";

/* §3.4. The POJO ships both tiers of result one flag apart: `*` marks a swap whose result is a
   legal enable1 word but not a common one — `over → oyer`, `the → tho`, `long → hong`. Those land
   as a dud when the payoff is a word you read out loud, so v1 lights only the common tier. Flip
   this to open the long tail with no rebuild. */
export const SERIFIN_OBSCURE = false;

/* word -> [{ i, to, obscure }] in table order. null until loadSerifin() resolves. */
let SWAPS = null;
let loading = null;

export function serifinReady() {
  return SWAPS !== null;
}

/* Idempotent, and safe to call from several places at once — they all await the same promise.
   The POJO is 56 KB and only this mode wants it, so it arrives on a dynamic import() the first
   time the player presses Pow! (the pattern ladderPOJO.js set). hasSerifinWords and wrapSerifin
   stay synchronous; the await lives in the one click handler that starts a round. */
export function loadSerifin() {
  if (SWAPS) return Promise.resolve();
  loading =
    loading ||
    import("./serifinPOJO.js").then(({ default: table }) => {
      const map = new Map();
      for (const word of Object.keys(table)) {
        const swaps = [];
        for (const tok of table[word].split(" ")) {
          const m = /^(\d+)([a-z])(\*?)$/.exec(tok);
          if (!m) continue; // a malformed entry is dropped, never guessed at
          swaps.push({ i: +m[1], to: m[2], obscure: m[3] === "*" });
        }
        if (swaps.length) map.set(word, swaps);
      }
      SWAPS = map;
    });
  return loading;
}

/* ── Which letters are live ───────────────────────────────────────────────────────────────────── */

/**
 * The live letters of one token, as [{ i, letters: [...] }] in left-to-right order, or [] for a
 * word with nothing to shoot. The index is into the token as typed.
 *
 * §3.5 rule 1: LOWERCASE ONLY. The table is a table of lowercase letterforms — a capital is a
 * different tool eight centuries older (the Roman chisel against the Carolingian pen) and gets its
 * own table if it ever gets one (§12.3). So the WORD is looked up case-insensitively, which keeps
 * `Dog` a target word, but a swap landing on a capital LETTER is dropped: `Dog` offers its `o`,
 * never its `D`.
 */
export function serifinCandidates(token) {
  if (!SWAPS || !/^[A-Za-z]{2,}$/.test(token)) return [];
  const lower = token.toLowerCase();
  const swaps = SWAPS.get(lower);
  if (!swaps) return [];

  const byIndex = new Map();
  for (const s of swaps) {
    if (!SERIFIN_OBSCURE && s.obscure) continue;
    if (token[s.i] !== lower[s.i]) continue; // the letter is capitalised — not a target
    if (!byIndex.has(s.i)) byIndex.set(s.i, []);
    byIndex.get(s.i).push(s.to);
  }
  return [...byIndex.entries()]
    .sort((a, b) => a[0] - b[0])
    .map(([i, letters]) => ({ i, letters }));
}

/** True if any letter in the sentence grows by one stroke. Same split and lookup as wrapSerifin,
 *  so the guard and the wrapper can never disagree about what is shootable. False until the table
 *  has loaded, which is why index.js awaits loadSerifin() before consulting it. */
export const hasSerifinWords = (sentence) => {
  if (!SWAPS) return false;
  return sentence.split(/\b/).some((token) => serifinCandidates(token).length > 0);
};

/* ── The markup (§5) ──────────────────────────────────────────────────────────────────────────── */

export const SF_WORD_CLASS = "sf-word";
export const SF_LETTER_CLASS = "sf-letter";

/* One target word. `data-sf` is the candidate list, `data-sf-from` the letter as typed and
   `data-sf-turn` where in the cycle we are — 0 being the original, so the authoritative state is
   (from, candidates, turn) and the glyph on screen is derivable from it rather than the other way
   round. The wrapper carries data-sf-word so §6.5's fixArticleBefore has a whole word to read. */
const serifinWordHTML = (token, live) => {
  let html = "";
  let at = 0;
  for (const { i, letters } of live) {
    html += token.slice(at, i);
    html +=
      `<span id="${SERIFIN_ID}" class="${SF_LETTER_CLASS}"` +
      ` data-sf="${letters.join(" ")}" data-sf-from="${token[i]}" data-sf-turn="0"` +
      `>${token[i]}</span>`;
    at = i + 1;
  }
  html += token.slice(at);
  return `<i class="${SF_WORD_CLASS}" data-sf-word="${token}">${html}</i>`;
};

/** Mark every letter in the sentence that grows by one stroke. A dead letter is plain text and a
 *  shot passes straight through it (§6.3) — the red underline on the live ones is the mode's whole
 *  affordance, since nothing else on screen says *this `o`, not that one*. */
export const wrapSerifin = (sentence) => {
  if (!SWAPS) return sentence;
  return sentence
    .split(/\b/)
    .map((token) => {
      const live = serifinCandidates(token);
      return live.length ? serifinWordHTML(token, live) : token;
    })
    .join("");
};

/* ── One hit (§6.1) ───────────────────────────────────────────────────────────────────────────── */

/** The whole cycle for a letter span: [original, ...candidates]. Computed from the span, which was
 *  computed once at wrap time — so the cycle a letter walks is fixed for the round. */
export const serifinCycle = (span) => {
  const from = span.getAttribute("data-sf-from") || span.textContent;
  const list = (span.getAttribute("data-sf") || "").split(" ").filter(Boolean);
  return [from, ...list];
};

/**
 * Advance one letter and return { letter, turn, wrapped } — the glyph the span should now show.
 * CALLER WRITES THE DOM, so the animation (§8) can draw the stroke before the glyph changes.
 *
 * CYCLING, NOT CHAINING (§6.1). The alternative is to recompute from the letter now on screen,
 * which gives chains (`cut → out → gut`) and costs the player every candidate they did not get
 * first: `adopt`'s `o` makes BOTH `adapt` and `adept`, and under chaining you are handed one of
 * them by list order and the other is gone, because `a` adds no stroke to anything. Cycling
 * guarantees every candidate is reachable, keeps the live-letter set and the frozen boxes static
 * for the whole round (§5.2), and is the rule Betar's Alphabet Slots already uses — including its
 * return to the original — so the player has met it. Chaining is open question §13 #1.
 */
export const serifinSwap = (span) => {
  const cycle = serifinCycle(span);
  if (cycle.length < 2) return null; // nothing to cycle through: that is a clank (§6.3)
  const turn = (Number(span.getAttribute("data-sf-turn")) || 0) + 1;
  const at = turn % cycle.length;
  span.setAttribute("data-sf-turn", String(at));
  return { letter: cycle[at], turn: at, wrapped: at === 0 };
};

/** The word a wrapper currently spells, read off the DOM rather than tracked — the letters are the
 *  only authority once a swap has landed. Kept in step with data-sf-word by serifinWordNow(). */
export const serifinWordNow = (wrapper) => {
  if (!wrapper) return "";
  const word = wrapper.textContent;
  wrapper.setAttribute("data-sf-word", word);
  return word;
};

/* ── The frozen boxes (§5.2) ──────────────────────────────────────────────────────────────────── */

/* The widest glyph a letter can ever show, measured in the face and at the size the sentence is
   actually set in. One offscreen canvas for the whole sentence.

   MUST RUN AFTER document.fonts.ready, or every box is frozen to a Palanquin metric and the first
   swap moves the line — which is the one thing §5.2 exists to prevent. freezeLetterBoxes awaits
   that itself, so callers can fire and forget: a round takes seconds to reach its first shot and
   the widths only have to be in place before a swap, never before the sentence renders. */
let measureCanvas = null;

function glyphWidths(font, glyphs) {
  measureCanvas = measureCanvas || document.createElement("canvas");
  const ctx = measureCanvas.getContext("2d");
  ctx.font = font;
  return glyphs.map((g) => ctx.measureText(g).width);
}

export async function freezeLetterBoxes(container) {
  const letters = [...container.querySelectorAll("." + SF_LETTER_CLASS)];
  if (!letters.length) return;

  const cs = getComputedStyle(container);
  const font = `${cs.fontStyle} ${cs.fontWeight} ${cs.fontSize} ${cs.fontFamily}`;

  // Ask for the face explicitly as well as waiting: fonts.ready only settles loads the layout has
  // already triggered, and a swap can be the first thing on the page to need a given glyph.
  try {
    if (document.fonts) {
      if (document.fonts.load) await document.fonts.load(font);
      if (document.fonts.ready) await document.fonts.ready;
    }
  } catch (e) {
    /* No FontFace API, or a face that refuses to load: measure in whatever is actually rendering.
       A box frozen to the fallback metric is wrong by a hair; a box never frozen is wrong by a
       whole line of sentence sliding sideways on the first hit. */
  }

  for (const span of letters) {
    const widths = glyphWidths(font, serifinCycle(span));
    const max = Math.max(...widths);
    if (!isFinite(max) || max <= 0) continue;
    // Ceiled to a hundredth: a sub-pixel shortfall clips the widest glyph's own stroke, which in
    // this mode is the thing the player is looking at.
    span.style.width = `${Math.ceil(max * 100) / 100}px`;
  }
}

/* ── THE DRAWN STROKE (§8) ────────────────────────────────────────────────────────────────────────

   The payoff of the whole mode: a pen draws the one stroke on, and the glyph becomes the other
   letter under it. This is also where §3.2's prune pays — every mapping that survived the table is
   one continuous stroke, so there is a path to draw for each of them and the animation can show
   exactly what the table claims.

   DEPARTURE FROM §8, STATED BECAUSE THE DOC SPECCED IT THE OTHER WAY. §8 asked for a table of SVG
   path STRINGS "in the letter box's own em units" (`"o>a": "M .86 .28 V .78"`). It is a table of
   FUNCTIONS of the measured glyph instead, and the reason is the mode's own claim: the stroke has
   to land exactly where the letterform grows, and a fixed 0–1 em path cannot be right for both a
   0.07 em `l` stem and a 0.52 em `o` bowl in a face whose metrics the table does not know. An
   authored constant would also quietly become a lie the moment §7's face is swapped — which §7.1
   says is allowed, provided the `a` stays single-storey. So the geometry is MEASURED, the same rule
   that gave projectileAnchor its number and freezeLetterBoxes its widths, and every entry below
   reads as a sentence about the letterform rather than as four magic numbers.

   What each function gets (all in CSS px, in the letter span's own box, y down):

     em             the font size
     sw             the pen's weight — MEASURED as the ink width of an `l`, i.e. the face's own stem
     base, xh       the baseline and the x-height line
     band, mid      the x-height band's height and its middle
     asc, desc      the TO glyph's own ink top and bottom (an ascender / a descender when it has
                    one, the x-height line / the baseline when it does not)
     from, to       {l, r, c} — each glyph's ink left, right and centre, where it actually sits in
                    the frozen box

   A mapping with no entry, or an entry that cannot be drawn at this size, returns null and the
   letter swaps with the red flash and no stroke — §8's honest degrade, which is also exactly what
   M3 shipped. NEVER a wrong stroke.

   WHY THE TO GLYPH'S INK BOX IS USED FOR THE NEW PART. A stem, a bar or a bowl that the result has
   and the original does not belongs to the RESULT, so it is positioned off the result's own ink
   (`o → a` puts the stem at the `a`'s right edge, not at a guess from the `o`'s). Where the stroke
   continues something already on screen — `u → o` closing the u's two stems, `h → b` closing the
   h's foot, `n → m` adding an arch beside the n's — it is anchored on the FROM glyph instead,
   because that is the ink it has to meet.

   WHICH END OF A STROKE IS ALLOWED TO BE WRONG, because one of them has to be. Both glyphs are
   centred in the SAME frozen box (§5.2), so a narrow original in a box sized for a wide result does
   not sit where the result's corresponding part will — an `l` centred in a box as wide as `b` has
   its stem ~0.2 em right of where the `b`'s stem lands, and an `n` in an `m`-wide box the same. The
   stroke therefore meets the ink that is on screen NOW at one end and the result's own ink at the
   other, and the far end is the one anchored on the result: a bowl's outer edge, an arch's second
   leg, the end of a tail — the parts standing in empty space, where the eye has nothing to compare
   them against and a misplacement would be the only thing visible. The near end sits on the
   original's ink, so it is right while it is drawn and shifts only when the glyph swaps under it —
   which happens as the mark is already fading, the one window in the beat where a hair of mismatch
   reads as the mark dissolving rather than as a misdraw. */

const n2 = (v) => Math.round(v * 100) / 100;
const vline = (x, y1, y2) => `M ${n2(x)} ${n2(y1)} V ${n2(y2)}`;
const hline = (y, x1, x2) => `M ${n2(x1)} ${n2(y)} H ${n2(x2)}`;
const line = (x1, y1, x2, y2) => `M ${n2(x1)} ${n2(y1)} L ${n2(x2)} ${n2(y2)}`;

/* Where a geometric `k`'s arm and leg meet the stem, as a fraction of the x-height band BELOW the
   x-height line. One constant for both k rows, because it is one fact about the letter — but it is
   a fact about the FACE's letter, so it is re-measured whenever §7's face changes.

   FITTED, not eyeballed: sweep the value and score how much of each drawn stroke lands inside the
   real `k`'s outline, then take the point where `h → k` and `l → k` agree. Run against Jost* that
   objective returns 0.42, which is the 0.41 this constant shipped with for a year — so the method
   reproduces the original measurement and can be trusted on a new face. Run against Questrial it
   returns 0.53 (h → k 0.785, l → k 0.784). The two rows pull in opposite directions on their own
   — `h → k` alone wants 0.66, `l → k` alone wants 0.35 — because `l → k`'s vertex sits on the
   l's stem, which §8.1 already says is not where the k's stem will be in the frozen box. The
   agreement point is the honest reading of "where the arm and leg meet the stem". */
const K_WAIST = 0.53;

/* A half-ellipse hung off a vertical chord: both ends on the same x, bulging `dx` to one side. This
   is what a bowl added to a stem IS — the pen leaves the stem, sweeps round and comes back to it —
   and drawing it top-to-bottom is the direction the hand goes. Sweep 1 bulges right in SVG's y-down
   space, 0 bulges left. */
const bowl = (x, yTop, yBot, dx) =>
  `M ${n2(x)} ${n2(yTop)} A ${n2(Math.abs(dx))} ${n2((yBot - yTop) / 2)} 0 0 ` +
  `${dx > 0 ? 1 : 0} ${n2(x)} ${n2(yBot)}`;

/* An arch: a semicircle over the top from one stem to the next, then straight down to the baseline.
   `l → h` and `n → m` are the same gesture at two different widths. */
const arch = (xFrom, xTo, g) => {
  const r = (xTo - xFrom) / 2;
  if (r <= 0.5) return null; // no room for a shoulder at this size
  return (
    `M ${n2(xFrom)} ${n2(g.xh + r)} A ${n2(r)} ${n2(r)} 0 0 1 ` +
    `${n2(xTo)} ${n2(g.xh + r)} L ${n2(xTo)} ${n2(g.base)}`
  );
};

/* A descending tail: down from a stem and hooked left, which is what `j` and `g` both end in. The
   hook's REACH is clamped to the result's own ink left, which is what keeps one helper honest for
   two very different letters — a `j`'s hook IS the glyph's left extent, so it runs the whole way,
   while a `g`'s stops around the middle of the bowl it hangs off and `to.l` is nowhere near it. The
   first version reached a flat 1.5 × the corner radius and sent `j`'s hook a full stem width
   outside its own box. */
const tail = (x, yFrom, g) => {
  const r = Math.min(g.em * 0.15, (g.desc - yFrom) * 0.7);
  if (r <= 0.5) return null;
  const end = Math.max(g.to.l + g.sw / 2, x - r * 1.2);
  return (
    `M ${n2(x)} ${n2(yFrom)} V ${n2(g.desc - r)} ` +
    `Q ${n2(x)} ${n2(g.desc)} ${n2(end)} ${n2(g.desc)}`
  );
};

/* The 27 strokes — one per surviving row of §3.1's table, keyed `from>to`. */
const STROKE = new Map(
  Object.entries({
    /* c — a ring open on the right. Everything added to it either closes that aperture or hangs a
       stem off it, and the stem closes it on the way past, which is why `c → a` is one stroke. */
    "c>o": (g) => {
      // The missing right arc of the ring, from the upper terminal round to the lower one.
      const rx = (g.to.r - g.to.l) / 2 - g.sw / 2;
      const ry = g.band / 2 - g.sw / 2;
      if (rx <= 0.5 || ry <= 0.5) return null;
      const APERTURE = (38 * Math.PI) / 180; // where a geometric `c` leaves off, near 1 o'clock
      const x = g.to.c + rx * Math.cos(APERTURE);
      const dy = ry * Math.sin(APERTURE);
      return (
        `M ${n2(x)} ${n2(g.mid - dy)} A ${n2(rx)} ${n2(ry)} 0 0 1 ` +
        `${n2(x)} ${n2(g.mid + dy)}`
      );
    },
    "c>a": (g) => vline(g.to.r - g.sw / 2, g.xh, g.base), // the a's own right stem
    "c>d": (g) => vline(g.to.r - g.sw / 2, g.asc, g.base), // the same stem, ascending
    "c>e": (g) => hline(g.mid, g.to.l, g.to.r), // the bar across the middle

    /* h → b: the right leg's foot carried back to the stem along the baseline. Bowed a little so it
       reads as a pen closing a shape rather than as an underline — .sf-letter's own red border sits
       below the descender, well clear, but a flat red line between the feet would still invite the
       comparison. Lifted half a stem off the baseline, where the bowl's own edge would be. */
    "h>b": (g) => {
      const y = g.base - g.sw / 2;
      const x1 = g.from.r - g.sw / 2;
      const x2 = g.from.l + g.sw / 2;
      return (
        `M ${n2(x1)} ${n2(y)} Q ${n2((x1 + x2) / 2)} ${n2(y + g.sw * 0.7)} ` +
        `${n2(x2)} ${n2(y)}`
      );
    },

    /* h → k: the h's shoulder and leg ARE the k's lower leg, so the only thing missing is the
       upper arm — one straight diagonal out of the junction where the shoulder leaves the stem,
       up and out to the right, with nothing removed. Drawn OUT of the stem rather than into it, so
       the arm visibly sprouts from ink that is already on screen, and the far end lands on the k's
       own right edge at the x-height, where a geometric k's arm terminates. You watch a straight
       arm arrive on the h's curved leg and then the font's real `k` lands under it — §8 beat 3,
       the same licence every row in this table draws on. */
    "h>k": (g) => line(g.from.l + g.sw / 2, g.xh + g.band * K_WAIST, g.to.r - g.sw / 2, g.xh),

    "i>j": (g) => tail(g.from.c, g.base, g), // the dot stays; the stem grows a tail

    /* i → l: join the stem to the tittle. The gap is real and visible — Questrial leaves 0.084 em
       of it between the stem's top and the dot (Jost* left 0.135) — so it is FILLED and the dot is
       absorbed rather
       than deleted: nothing is erased, and nothing is lengthened either, which is what makes this
       the cleanest addition in the table and the shortest stroke in it. It runs past the dot to
       `asc`, the l's OWN ink top, since the l stands taller than the i's tittle. The two stems
       land on the same x in the frozen box (the `i` is the widest letter in its own cycle, so it
       sets the box), making this the one entry whose BOTH ends are right. FALSE in a face whose
       `i` has a foot serif — the serif would survive into a letter that must not have one, which
       is why that is now a standing constraint on the face (§7.1) and not a note about this row. */
    "i>l": (g) => vline(g.from.c, g.xh, g.asc),

    /* l — a bare ascending stem, and the richest row in the table: four letters are that stem plus
       one more thing. The stem is already on screen, so each stroke is anchored on it. */
    "l>t": (g) => hline(g.xh, g.to.l, g.to.r), // the crossbar, at the x-height line
    "l>b": (g) => bowl(g.from.c, g.xh, g.base, g.to.r - g.sw / 2 - g.from.c),
    "l>d": (g) => bowl(g.from.c, g.xh, g.base, g.to.l + g.sw / 2 - g.from.c),
    "l>h": (g) => arch(g.from.c, g.to.r - g.sw / 2, g),
    /* l → k: one motion that touches the stem once on the way through — in from the arm's top
       terminal, down to the waist, out again to the leg's foot. Two segments, no lift, which is
       why it is a row at all: §3.2 cut it counting SEGMENTS and §13 #7 settled the test as the
       PEN. Both ends stand in empty space and are anchored on the k's own right edge, where a
       misplacement would be the only visible thing; the stem it passes through is the ink that is
       already there. The honest neighbour of `h → k`, since an h's ascender IS an l. */
    "l>k": (g) => {
      const xj = g.from.c; // the l's stem, which is the k's
      const x = g.to.r - g.sw / 2;
      if (x <= xj + 1) return null;
      return (
        `M ${n2(x)} ${n2(g.xh)} L ${n2(xj)} ${n2(g.xh + g.band * K_WAIST)} ` +
        `L ${n2(x)} ${n2(g.base)}`
      );
    },

    /* n → m: one more arch, and the only row where the result is much wider than the original —
       `m` is the widest letter in the lowercase. The new shoulder starts on the n's own right leg
       and lands on the m's. */
    "n>m": (g) => arch(g.from.r - g.sw / 2, g.to.r - g.sw / 2, g),

    /* o — a closed ring, and the biggest source letter in the table by a long way (§2): seven
       letters are a ring plus one stroke. `o → a` alone is 769 swaps, which is the whole reason the
       mode wears a face with a single-storey `a` (§7.1) — in a double-storey face this one line
       would be a lie. */
    "o>a": (g) => vline(g.to.r - g.sw / 2, g.xh, g.base), // the stem down the right side
    "o>e": (g) => hline(g.mid, g.to.l, g.to.r), // the bar across
    "o>b": (g) => vline(g.to.l + g.sw / 2, g.asc, g.base), // ascender, left
    "o>d": (g) => vline(g.to.r - g.sw / 2, g.asc, g.base), // ascender, right
    "o>p": (g) => vline(g.to.l + g.sw / 2, g.xh, g.desc), // descender, left
    "o>q": (g) => vline(g.to.r - g.sw / 2, g.xh, g.desc), // descender, right
    // Single-storey only, and flagged as such in the build script: in a two-storey `g` this is a
    // second bowl, which is not one stroke and the row would have to go (§3.2).
    "o>g": (g) => tail(g.to.r - g.sw / 2, g.xh, g),

    /* r → n: the shoulder stops in mid-air; carry it down to the baseline and it is an arch. Drawn
       as one curve leaving the r's own terminal and bending down onto the n's right leg, rather
       than as a detached vertical — the stroke is a continuation, so it has to start where the ink
       already ends. */
    "r>n": (g) => {
      const yTop = g.xh + g.band * 0.26;
      const x1 = g.from.r - g.sw / 2;
      const x2 = g.to.r - g.sw / 2;
      if (x2 <= x1 + 0.5) return vline(x1, yTop, g.base);
      return `M ${n2(x1)} ${n2(yTop)} Q ${n2(x2)} ${n2(yTop)} ${n2(x2)} ${n2(g.base)}`;
    },

    /* r → m: the shoulder stops in mid-air, so carry it down to the baseline and straight on over
       a second arch — which is how a hand writes an `m`, and is the whole argument for the row.
       ONE subpath with no moveto in it: the `V` back up the leg just drawn RETRACES ink already
       laid, so the dash animation puts no new mark on screen while the pen returns, which is what
       the hand's own retrace looks like. The m's middle stem is its ink centre and its third stem
       is its right edge, so both legs are the RESULT's own; the first one leans left, because a
       centred `r` in an `m`-wide box sits ~0.29 em right of where the m's stem lands — the widest
       such gap in the table (§8.1), and it leans the way the glyph is about to move. This is the
       row to DROP first if that reads badly, never a reason to unfreeze the box (§5.2). */
    "r>m": (g) => {
      const x1 = g.from.r - g.sw / 2; // the r's own terminal, stopped in mid-air
      const x2 = g.to.c; // the m's middle stem is its centre
      const x3 = g.to.r - g.sw / 2; // and its third is its right edge
      const r = (x3 - x2) / 2;
      if (r <= 0.5) return arch(x1, x3, g); // no room for two shoulders at this size: draw one
      const yTop = g.xh + g.band * 0.26; // where the r's terminal sits — r>n's own number
      return (
        `M ${n2(x1)} ${n2(yTop)} Q ${n2(x2)} ${n2(yTop)} ${n2(x2)} ${n2(g.base)} ` +
        `V ${n2(g.xh + r)} A ${n2(r)} ${n2(r)} 0 0 1 ${n2(x3)} ${n2(g.xh + r)} ` +
        `L ${n2(x3)} ${n2(g.base)}`
      );
    },

    /* u → o: close the top. A shallow bow rather than a flat bar — the two stems are being joined
       over the counter, and the apex of the bow is THE RING'S OWN TOP, measured.

       It used to rise by a flat `sw * 1.2`, a number tuned to Jost*'s overshoot, and that is the
       one row in this table that was secretly face-specific: scored against the real `o`'s ink it
       ran 1.000 on Jost* but 0.236 on Questrial, 0.656 on Didact Gothic and 0.005 on Poppins —
       a bow floating clear of the ring it is supposed to be completing. `g.asc` is already the
       RESULT's own ink top (strokeGeometry measures it off the `o`, overshoot included), so the
       apex goes there, inset half a pen so the stroke's outer edge lands on the ring rather than
       its centre-line. A quadratic's apex is the midpoint of its endpoint and its control point,
       hence the doubling. Measured after: Jost* 1.000 (unchanged), Questrial 0.784, Didact 0.819,
       Poppins 0.840 — better or equal on every face, which is what a measured number buys over a
       tuned one. */
    "u>o": (g) => {
      const y = g.xh + g.sw / 2;
      const x1 = g.from.l + g.sw / 2;
      const x2 = g.from.r - g.sw / 2;
      if (x2 <= x1 + 0.5) return null;
      const yc = 2 * (g.asc + g.sw / 2) - y; // control point: apex on the o's own ink top
      return `M ${n2(x1)} ${n2(y)} Q ${n2((x1 + x2) / 2)} ${n2(yc)} ${n2(x2)} ${n2(y)}`;
    },

    /* u → a: close the top — and in THIS face that makes an `a`, not an `o`. Questrial's `u`
       carries a straight right stem running the full x-height up from the baseline, as Jost*'s did
       (x 370–450, y 0–460 of 1000 upem), and that stem already IS the single-storey `a`'s, so one
       stroke over the top leaves a bowl with a round left side and a straight right one, which is
       the `a` exactly. The hood lifts off the left stem's top, crests a hair ABOVE the x-height —
       a geometric `a`'s apex overshoots, 470 against 460 — and comes down VERTICALLY onto the
       right stem BELOW its top, which is the entire difference from `u>o`'s flat bow and worth
       drawing the two side by side for. §13 #8, settled by measuring the glyph rather than
       reasoning about Futura's conventions; in a face whose `u` is a continuous curve up the right
       with no stem, this row is false and `u>o` is the true one. */
    "u>a": (g) => {
      const x1 = g.from.l + g.sw / 2; // the u's left stem
      const x2 = g.from.r - g.sw / 2; // and its right, which is the a's
      if (x2 <= x1 + 1) return null;
      const dx = x2 - x1;
      return (
        `M ${n2(x1)} ${n2(g.xh)} C ${n2(x1 + dx * 0.42)} ${n2(g.xh - g.sw * 0.7)} ` +
        `${n2(x2)} ${n2(g.xh - g.sw * 0.2)} ${n2(x2)} ${n2(g.xh + g.band * 0.29)}`
      );
    },

    "v>y": (g) => vline(g.from.c, g.base, g.desc), // the tail, straight down off the vertex

    /* v → w: carry the zigzag on. The pen is already standing at the v's top-right terminal, so it
       goes down to a second vertex and back up — one unbroken motion, two segments, no lift, which
       is what §3.2's "two more strokes" was counting wrongly. The vertex sits at `desc`, the w's
       own ink bottom, because a pointed vertex overshoots the baseline where the face gives it one
       (Jost* 0.035 em; Questrial 0.000, so `desc` simply resolves to the baseline) and a new
       `v` stopping dead on the line would be the one visibly wrong thing about it.

       MEASURED, AND THE ROW'S OWN WEAKNESS: a `w` is only 0.23 em wider than a `v`, and a centred
       `v` spends half of that on each side, so the added half has ~0.115 em of slack — at a 40 px
       em it is 4.6 px wide against a 3.2 px pen, i.e. a narrow hairpin rather than a second `v`.
       That is not a drawing error, it is the frozen box (§5.2): a `w` is not a `v` plus a `v`, and
       its middle peak lands where the centred v's VERTEX was. The shipped `n → m` arch is the same
       scale of small (2.55 px radius at 40 px), so this may read fine — but if either reads badly
       the fix is to drop the ROW, never to unfreeze the box. */
    "v>w": (g) => {
      const x1 = g.from.r - g.sw / 2; // the v's own right terminal
      const x3 = g.to.r - g.sw / 2; // the w's
      if (x3 <= x1 + 1) return null;
      return (
        `M ${n2(x1)} ${n2(g.xh)} L ${n2((x1 + x3) / 2)} ${n2(g.desc)} ` +
        `L ${n2(x3)} ${n2(g.xh)}`
      );
    },
  }),
);

/* ── Measuring the glyph the stroke has to land on ────────────────────────────────────────────── */

/* Ink boxes come off the same offscreen canvas freezeLetterBoxes already uses, cached per
   font+character because a round asks for the same handful of glyphs over and over.

   THE FACE'S LOAD STATE IS PART OF THE KEY. Questrial arrives on `font-display: swap`, so a measurement
   taken before the woff2 lands is a Palanquin metric — and a cache that could not tell the two
   apart would go on scoring every stroke of the round against the fallback. The Scriptorium's own
   font scorer hit exactly this and answered it the same way (docs/inklings-typography.md §M2.5). */
const inkCache = new Map();

function glyphInk(font, ch) {
  let loaded = true;
  try {
    loaded = !document.fonts || !document.fonts.check || document.fonts.check(font);
  } catch (e) {
    /* A font string the UA won't parse: treat it as settled rather than re-measuring forever. */
  }
  const key = `${font}|${loaded ? 1 : 0}|${ch}`;
  const hit = inkCache.get(key);
  if (hit !== undefined) return hit;

  measureCanvas = measureCanvas || document.createElement("canvas");
  const ctx = measureCanvas.getContext("2d");
  ctx.font = font;
  const m = ctx.measureText(ch);
  // TextMetrics' actual* fields are what make any of this possible. Without them there is no ink
  // box, so there is no stroke — the letter still swaps, it just swaps bare (§8's degrade).
  const ink =
    typeof m.actualBoundingBoxAscent === "number" &&
    typeof m.actualBoundingBoxRight === "number"
      ? {
          adv: m.width,
          // actualBoundingBoxLeft measures LEFTWARD from the alignment point, so it is negative for
          // a glyph with the usual positive left side bearing. Negate it to get an offset.
          left: -(m.actualBoundingBoxLeft || 0),
          right: m.actualBoundingBoxRight,
          top: m.actualBoundingBoxAscent, // above the baseline
          bottom: m.actualBoundingBoxDescent || 0, // below it
        }
      : null;
  inkCache.set(key, ink);
  return ink;
}

/* The baseline, MEASURED rather than derived from the font's ascent and half-leading. A zero-sized
   inline-block on `vertical-align: baseline` has its bottom margin edge ON the baseline (it has no
   line boxes of its own, so that is the rule), which makes its top the baseline to the pixel. It
   adds no width and no height, so the line box and the centred glyph are untouched, and it is gone
   again before anything else reads the span. */
function baselineY(span) {
  const probe = document.createElement("i");
  probe.style.cssText =
    "display:inline-block;width:0;height:0;vertical-align:baseline;";
  span.appendChild(probe);
  const y = probe.getBoundingClientRect().top;
  probe.remove();
  return y;
}

function strokeGeometry(span, from, to) {
  const cs = getComputedStyle(span);
  const font = `${cs.fontStyle} ${cs.fontWeight} ${cs.fontSize} ${cs.fontFamily}`;
  const em = parseFloat(cs.fontSize) || 16;

  const fi = glyphInk(font, from);
  const ti = glyphInk(font, to);
  const xi = glyphInk(font, "x"); // the x-height line, straight off the face
  const li = glyphInk(font, "l"); // the face's own stem width — the pen's weight
  if (!fi || !ti || !xi || !li) return null;

  const rect = span.getBoundingClientRect();
  const bb = parseFloat(cs.borderBottomWidth) || 0;
  const w = rect.width;
  const h = Math.max(1, rect.height - bb); // the content box; the red underline sits outside it
  const base = baselineY(span) - rect.top;
  if (!isFinite(base) || base <= 0 || base > h + em) return null;

  // text-align: center, so each glyph's advance box is centred in the frozen width (§5.2).
  const place = (ink) => {
    const x0 = (w - ink.adv) / 2;
    return { l: x0 + ink.left, r: x0 + ink.right, c: x0 + ink.adv / 2 };
  };

  const xh = base - xi.top;
  const band = base - xh;
  if (band <= 1) return null;
  const sw = Math.min(em * 0.16, Math.max(em * 0.04, li.right - li.left));

  return {
    em,
    sw,
    w,
    h,
    base,
    xh,
    band,
    mid: (base + xh) / 2,
    // An ascender/descender only where the RESULT actually has one: `o → a` must not reach for an
    // ascender it hasn't got, and `o → e` must not dip below the baseline.
    asc: base - Math.max(ti.top, xi.top),
    desc: base + Math.max(ti.bottom, 0),
    from: place(fi),
    to: place(ti),
  };
}

/* ── Drawing it (§8's three beats) ────────────────────────────────────────────────────────────── */

export const SF_DRAW_MS = 220; // the stroke travelling
export const SF_FADE_MS = 200; // the mark settling into the sentence's ink

const SVG_NS = "http://www.w3.org/2000/svg";
/* One stroke in the air per letter. Shots land ~1.4s apart so this is a guard rather than a live
   path, but a second bolt can arrive mid-draw and two marks on one glyph read as a glitch. WeakMap
   because #output is rewritten wholesale on a new sentence and these nodes go with it. */
const inFlight = new WeakMap();

const reducedMotion = () => {
  try {
    return !!window.matchMedia?.("(prefers-reduced-motion: reduce)").matches;
  } catch (e) {
    return false;
  }
};

/**
 * Draw the stroke that turns `from` into `to` over the letter in `span`, then call `onSwap` to let
 * the caller write the new glyph under it and fade the mark into the ink.
 *
 * Returns TRUE when it has taken responsibility for calling `onSwap` (after SF_DRAW_MS), and FALSE
 * when there is nothing to draw — no path for this mapping, no TextMetrics to measure with, reduced
 * motion — in which case the caller swaps immediately and the mode behaves exactly as M3 shipped.
 * There is no third outcome and never a wrong stroke (§8).
 *
 * The SVG is absolutely positioned inside #output and never joins the line box — the cartouche's
 * rule — so it can neither reflow the sentence it is drawn on nor be clipped by it, and it dies
 * with the sentence the moment #output is rewritten. #output is `position: fixed` with no border or
 * padding, so its client rect IS the origin.
 */
export function drawSerifinStroke(span, from, to, ink, onSwap) {
  const build = STROKE.get(`${from}>${to}`);
  const out = span.closest && span.closest("#output");
  if (!build || !out || reducedMotion()) return false;

  const g = strokeGeometry(span, from, to);
  if (!g) return false;
  let d = null;
  try {
    d = build(g);
  } catch (e) {
    d = null;
  }
  if (!d) return false;

  inFlight.get(span)?.remove();

  const host = out.getBoundingClientRect();
  const rect = span.getBoundingClientRect();
  const svg = document.createElementNS(SVG_NS, "svg");
  svg.setAttribute("class", "sf-stroke");
  svg.setAttribute("width", String(g.w));
  svg.setAttribute("height", String(g.h));
  svg.setAttribute("viewBox", `0 0 ${n2(g.w)} ${n2(g.h)}`);
  svg.setAttribute("fill", "none");
  svg.setAttribute("aria-hidden", "true");
  svg.style.left = `${rect.left - host.left}px`;
  svg.style.top = `${rect.top - host.top}px`;

  const path = document.createElementNS(SVG_NS, "path");
  path.setAttribute("d", d);
  path.setAttribute("stroke", ink);
  path.setAttribute("stroke-width", String(n2(g.sw)));
  path.setAttribute("stroke-linecap", "round");
  path.setAttribute("stroke-linejoin", "round");
  svg.appendChild(path);
  out.appendChild(svg);
  inFlight.set(span, svg);

  const drop = () => {
    svg.remove();
    if (inFlight.get(span) === svg) inFlight.delete(span);
  };
  let swapped = false;
  const swap = () => {
    if (swapped) return;
    swapped = true;
    onSwap();
  };

  const len = path.getTotalLength ? path.getTotalLength() : 0;
  if (!len || !path.animate) {
    // No WAAPI, or a path whose length can't be had: show the stroke whole rather than not at all.
    setTimeout(() => {
      swap();
      svg.style.transition = `opacity ${SF_FADE_MS}ms ease-in`;
      svg.style.opacity = "0";
      setTimeout(drop, SF_FADE_MS + 60);
    }, SF_DRAW_MS);
    return true;
  }

  path.style.strokeDasharray = `${len}`;
  const draw = path.animate(
    [{ strokeDashoffset: `${len}` }, { strokeDashoffset: "0" }],
    { duration: SF_DRAW_MS, easing: "ease-out", fill: "forwards" },
  );
  draw.onfinish = () => {
    swap();
    // Beat 3: the mark fades from her red into the sentence's own ink, so the new letter absorbs
    // the stroke that made it. The letter itself is never left coloured (§10.2).
    const fade = path.animate(
      [
        { stroke: ink, opacity: 1 },
        { stroke: "whitesmoke", opacity: 0 },
      ],
      { duration: SF_FADE_MS, easing: "ease-in", fill: "forwards" },
    );
    fade.onfinish = drop;
  };
  /* The swap is the one thing in the beat that MUST happen: a stroke that fails to finish would
     otherwise leave the letter permanently unchanged against a shot that hit it. An animation can
     be cancelled (a reflow, a tab going to sleep), so the timer is the floor under onfinish and
     `swapped` makes whichever arrives first the only one that counts. */
  setTimeout(swap, SF_DRAW_MS + 90);
  setTimeout(drop, SF_DRAW_MS + SF_FADE_MS + 500);
  return true;
}
